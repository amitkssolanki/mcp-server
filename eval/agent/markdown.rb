# frozen_string_literal: true

module Eval
  module Agent
    # Renders an experiment's JSON report as Markdown. It holds data only: the
    # method, the metrics, one row per question and every non-correct run with
    # what the agent called and answered. Interpretation belongs in a
    # hand-written section appended after the generated part, marked as such.
    class Markdown
      def initialize(report)
        @r = report
      end

      def render
        m = @r[:method]
        x = @r[:metrics]
        lines = []
        lines << "# Agent evaluation: #{@r[:experiment]}"
        lines << ""
        lines << "_Generated by `bin/rails eval:agent` from #{@r[:experiment]}.json. Raw event logs: `tmp/agent/#{@r[:experiment]}/` (not committed)._"
        lines << ""
        lines << "## Method"
        lines << ""
        lines << "| | |"
        lines << "|---|---|"
        lines << "| Execution | #{m[:execution]} (#{m[:claude_code_version]}) |"
        lines << "| Model | `#{m[:model]}` |"
        lines << "| Billing path (apiKeySource per run) | #{m[:api_key_sources].map { |k, v| "`#{k}` x#{v}" }.join(', ')} |"
        lines << "| Size | #{m[:questions]} questions x #{m[:runs_per_question]} runs = #{m[:total_runs]} runs |"
        lines << "| Tool definitions | digest `#{m[:tools][:digest]}`; frozen baseline: #{m[:tools][:matches_frozen_baseline] ? 'yes' : "no (changed: #{m[:tools][:changed_tools].join(', ')})"} |"
        lines << "| Commit | `#{m[:git_commit]}` |"
        lines << "| Run window (UTC) | #{m[:started_at]} to #{m[:finished_at]} |"
        lines << ""
        lines << "## Metrics"
        lines << ""
        lines << "| Metric | Value |"
        lines << "|---|---:|"
        lines << "| Answer accuracy (agrees with the oracle) | #{x[:answer_accuracy_pct]}% |"
        lines << "| Tool-selection accuracy | #{x[:tool_selection_accuracy_pct]}% |"
        lines << "| Argument accuracy | #{x[:argument_accuracy_pct]}% |"
        lines << "| Questions correct on every run | #{x[:questions_correct_every_run]} / #{m[:questions]} |"
        lines << "| Questions with identical verdict and answer on every run | #{x[:questions_consistent]} / #{m[:questions]} |"
        lines << "| Verdicts | #{x[:verdicts].map { |k, v| "#{k} #{v}" }.join(', ')} |"
        lines << "| Mean tool calls per run | #{x[:mean_tool_calls]} |"
        lines << "| Mean duration per run | #{x[:mean_duration_s]}s |"
        lines << "| Tokens (input / output / cache read / cache write) | #{x[:tokens].values.join(' / ')} |"
        lines << "| Notional cost reported by Claude Code | $#{x[:notional_cost_usd]} (subscription; not billed per token) |"
        lines << ""
        lines << "## Per question"
        lines << ""
        lines << "| Question | Expected | Correct | Tool | Args | Verdicts |"
        lines << "|---|---:|---:|---:|---:|---|"
        @r[:questions].each do |q|
          lines << "| **#{q[:id]}** #{q[:prompt].gsub('|', '\\|')} | #{q[:expected]} | #{q[:correct]}/#{q[:runs]} | " \
                   "#{q[:tool_ok]}/#{q[:runs]} | #{q[:args_ok]}/#{q[:runs]} | #{q[:verdicts].join(', ')} |"
        end
        lines << ""
        lines << "## Runs that were not correct"
        lines << ""
        misses = @r[:runs].reject { |r| r[:grade][:correct] }
        lines << "None." if misses.empty?
        misses.each do |r|
          g = r[:grade]
          lines << "### #{r[:question_id]}, run #{r[:run_index]}: #{g[:verdict]}"
          lines << ""
          lines << "- expected `#{g[:expected]}`, answered `#{g[:answer].inspect}`; tool ok: #{g[:tool_ok]}, args ok: #{g[:args_ok]}"
          lines << "- error: #{r[:run][:error]}" if r[:run][:error]
          r[:run][:tool_calls].each do |c|
            lines << "- call `#{c[:tool]}` `#{JSON.generate(c[:arguments] || {})}`#{' (error)' if c[:is_error]}"
          end
          final = r[:run][:final_text].to_s.strip.gsub(/\s+/, " ")
          lines << "- final answer: \"#{final[0, 400]}#{'...' if final.length > 400}\""
          lines << ""
        end
        lines.join("\n") + "\n"
      end
    end
  end
end
